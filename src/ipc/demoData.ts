export function demoSelection(
  strategy: CouncilStrategy,
  pinned: readonly string[] = [],
): CouncilSelection {
  const mapping = PANEL_BY_STRATEGY[strategy];
  const rank = strategy === "steady" ? 0 : strategy === "clash" ? 1 : 2;
  const seats = (Object.keys(mapping) as LayerKey[]).map((layer) => {
    const masterId = mapping[layer];
    const master = DEMO_MASTERS.find((item) => item.id === masterId);
    const scores = CANDIDATE_SCORES[masterId] ?? [0.5, 0.5, 0.5];
    return {
      masterId,
      name: master?.name ?? masterId,
      domain: master?.domain ?? "",
      layers: CANDIDATE_LAYERS[masterId] ?? [layer],
      layer,
      score: scores[rank],
      pinned: pinned.includes(masterId),
    };
  });
  return {
    strategy,
    size: seats.length,
    seats,
    layers: (Object.keys(mapping) as LayerKey[]).sort(),
    gaps: [],
  };
}


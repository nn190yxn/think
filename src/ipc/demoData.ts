/** 逐席发言：按席位归组该席位各轮发言并合成状态。 */
export function demoSeatSpeech(rotation: number): readonly CouncilSeatSpeech[] {
  const panel =
    DEMO_SESSION.panels.find((item) => item.rotation === rotation) ??
    DEMO_SESSION.panels[DEMO_SESSION.panels.length - 1]!;
  const mapping = PANEL_BY_STRATEGY[panel.strategy];
  return panel.masterIds.map((masterId): CouncilSeatSpeech => {
    const master = DEMO_MASTERS.find((item) => item.id === masterId);
    const layer =
      (Object.keys(mapping) as LayerKey[]).find((key) => mapping[key] === masterId) ?? "fa";
    const rounds = DEMO_SESSION.turns
      .filter(
        (turn) =>
          turn.panelRotation === rotation &&
          turn.masterId === masterId &&
          (turn.role === "answer" || turn.role === "cross"),
      )
      .map((turn) => ({
        round: turn.round,
        role: turn.role,
        content: turn.content,
        status: turn.status,
        errorCode: turn.errorCode,
        createdAt: turn.createdAt,
      }));
    const status =
      rounds.length === 0
        ? "pending"
        : rounds.some((round) => round.status !== "ok")
          ? "failed"
          : "answered";
    return {
      masterId,
      masterName: master?.name ?? masterId,
      layer,
      status,
      rounds,
    };
  });
}

